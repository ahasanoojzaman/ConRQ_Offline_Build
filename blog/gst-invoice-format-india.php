  <h1 style="font-size:2rem;margin-top:12px;margin-bottom:10px">GST Invoice Format in India: A Complete Guide for Small Businesses</h1>
  <p class="lead">A GST invoice is a legal document, not just a receipt. Getting the format wrong can mean rejected input tax credit for your customer, notices during audits, or simply a messier set of books at return-filing time. Here's what every GST-registered business actually needs on an invoice.</p>

  <h2>What a GST invoice must legally contain</h2>
  <p>Under India's GST rules, a tax invoice issued by a registered business must include:</p>
  <ul>
    <li><strong>Invoice number and date</strong> — a consecutive serial number, unique for the financial year</li>
    <li><strong>Supplier details</strong> — name, address, and GSTIN</li>
    <li><strong>Recipient details</strong> — name, address, and GSTIN (if the recipient is registered)</li>
    <li><strong>HSN or SAC code</strong> for each good or service supplied</li>
    <li><strong>Description, quantity, and unit</strong> of goods or services</li>
    <li><strong>Taxable value</strong> of the supply</li>
    <li><strong>Rate and amount of tax</strong> — CGST and SGST for an intra-state sale, or IGST for an inter-state sale</li>
    <li><strong>Place of supply</strong>, particularly for inter-state transactions</li>
    <li><strong>Whether tax is payable on reverse charge</strong>, where applicable</li>
    <li><strong>Signature</strong> of the supplier or an authorised representative (a digital signature is acceptable on electronically generated invoices)</li>
  </ul>

  <div class="callout">
    <strong>Why place of supply matters more than it looks:</strong> it is what determines whether a sale is taxed as CGST+SGST or IGST. Get it wrong and the tax split on the invoice is wrong too — this is one of the most common errors on manually written bills.
  </div>

  <h2>Common mistakes small businesses make</h2>
  <h3>1. Non-sequential invoice numbers</h3>
  <p>Invoice numbers must run in a consistent, traceable sequence for the financial year. Manually numbered books or ad-hoc spreadsheets often end up with duplicates or gaps, which stands out immediately during a GST audit.</p>

  <h3>2. Wrong or missing HSN/SAC codes</h3>
  <p>Every line item needs the correct HSN (for goods) or SAC (for services) code. Using a generic or incorrect code doesn't just look sloppy — it can misclassify the applicable tax rate entirely.</p>

  <h3>3. Incorrect CGST/SGST vs IGST split</h3>
  <p>This comes back to place of supply. A sale to a customer in the same state should split tax as CGST+SGST; a sale to a different state should charge IGST instead. Manually calculating this on every invoice is where errors creep in fastest.</p>

  <h3>4. Missing e-way bill or transport details</h3>
  <p>For the movement of goods above the applicable value threshold, an e-way bill is required, and invoices for those shipments should carry vehicle and transport details. Businesses that generate delivery challans or invoices for goods in transit need a place to record this consistently.</p>

