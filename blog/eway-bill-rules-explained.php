  <h1 style="font-size:2rem;margin-top:12px;margin-bottom:10px">E-Way Bill Rules in India: When You Need One and What Must Be On It</h1>
  <p class="lead">If your business moves goods between locations, customers, or states, an e-way bill is often a legal requirement — not an optional formality. Here is what it actually is and when it applies.</p>

  <h2>What an e-way bill is</h2>
  <p>An e-way bill (electronic way bill) is a document generated on the government's e-way bill portal that must accompany the movement of goods above a certain consignment value, whether that movement is a sale, a stock transfer between your own locations, or goods sent for job work. It exists so tax authorities can verify that goods in transit match what has been declared.</p>

  <h2>When you need one</h2>
  <p>Broadly, an e-way bill is required when the value of goods being transported crosses the threshold set under GST rules, for both inter-state and (in most states) intra-state movement. There are some exemptions for specific goods and situations.</p>
  <div class="callout">
    The exact value threshold and specific exemptions are set by GST rules and can be updated by the government. Always confirm the current threshold on the official e-way bill portal (ewaybillgst.gov.in) or with your chartered accountant before relying on a specific number — this article will not guess at a figure that might be out of date by the time you read it.
  </div>

  <h2>What information it requires</h2>
  <p>Generating an e-way bill needs details that should already be on a well-formed invoice or delivery challan:</p>
  <ul>
    <li>GSTIN and details of the supplier and recipient</li>
    <li>Invoice or challan number and date</li>
    <li>HSN code and value of goods being transported</li>
    <li>Transport details — vehicle number, or transporter ID if moved by a third party</li>
    <li>Place of dispatch and place of delivery</li>
  </ul>
  <p>This is exactly why keeping vehicle number, transport mode, and reference details recorded consistently on your invoices, purchase bills and delivery challans matters — it is the same information you will need again when generating the e-way bill itself.</p>

  <h2>Delivery challans vs invoices for goods movement</h2>
  <p>Not every movement of goods is a sale. Sending goods for job work, moving stock between your own warehouses, or sending goods on approval are common situations where a <strong>delivery challan</strong> — not a tax invoice — is the correct document, even though an e-way bill may still be required for the movement itself. Keeping challans and invoices as distinct, properly numbered document types (rather than improvising with one or the other) makes this much easier to get right.</p>

  <h2>Generating the e-way bill itself</h2>
  <p>The e-way bill is generated directly on the government portal (or via GSP/API integrations connected to it) — no billing software can generate an officially valid e-way bill on your behalf without connecting to that system. What good software <em>can</em> do is make sure every piece of information you will need to enter is already recorded accurately on the source document, so generating the e-way bill is a five-minute copy-paste rather than a search through paperwork.</p>

